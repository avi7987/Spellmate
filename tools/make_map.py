"""Generates data/map.json: a 30x30 point-symmetric world (fair for both sides).

Legend: . plain  f forest  h hill  ~ water  = bridge  m crystal mine
        p palace floor  # palace wall  G gate  T tower (on the wall)
The Sun palace is at the bottom, the Void palace at the top (rotated 180).
Run: python3 tools/make_map.py > data/map.json
"""
import json
import random

W = H = 30
g = [["." for _ in range(W)] for _ in range(H)]  # g[rank][file]


def put(f, r, c):
    g[r][f] = c


# --- bottom half (ranks 0..13), mirrored later --------------------------
rnd = random.Random(42)
# forest clusters
for cx, cy, n in [(4, 6, 7), (24, 8, 8), (9, 11, 6), (20, 12, 6), (2, 12, 4), (27, 3, 5)]:
    for _ in range(n):
        f, r = cx + rnd.randint(-2, 2), cy + rnd.randint(-1, 1)
        if 0 <= f < W and 0 <= r < 14:
            put(f, r, "f")
# hills
for f, r in [(7, 8), (8, 8), (22, 5), (23, 5), (14, 11), (15, 11), (1, 9), (28, 10)]:
    put(f, r, "h")
# crystal mines: 2 near the palace, 2 contested near the river
for f, r in [(7, 3), (22, 3), (4, 11), (25, 12)]:
    put(f, r, "m")
# palace: files 11..18, ranks 0..6
for r in range(0, 7):
    for f in range(11, 19):
        edge = f in (11, 18) or r == 6
        put(f, r, "#" if edge else "p")
put(14, 6, "G")
put(11, 6, "T")
put(18, 6, "T")
# river ranks 14 and 15 (handled for both halves below)

# --- mirror into the top half (point symmetry) ----------------------------
for r in range(0, 14):
    for f in range(W):
        g[H - 1 - r][W - 1 - f] = g[r][f]
for r in (14, 15):
    for f in range(W):
        g[r][f] = "~"
    for f in (3, 4, 14, 15, 25, 26):
        g[r][f] = "="

rows = ["".join(g[r]) for r in range(H - 1, -1, -1)]  # top row first
army = {"o3": "king", "p4": "queen", "n5": "miner", "o5": "pawn", "p5": "pawn"}
print(json.dumps({
    "_comment": "Generated by tools/make_map.py. Rows from the top (rank 30, Void) to the bottom (rank 1, Sun). "
                ". plain  f forest  h hill  ~ water  = bridge  m crystal mine  p palace floor  # wall  G gate  T tower",
    "rows": rows,
    "_army": "Starting army of the Sun (bottom). The Void army is the same, rotated 180 degrees. Files a-z then A-D (30 files), ranks 1-30.",
    "army": army,
}, ensure_ascii=False, indent="\t"))
